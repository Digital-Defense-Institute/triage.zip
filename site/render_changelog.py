#!/usr/bin/env python3
"""Render the shared dated changelog to static HTML and repository Markdown."""
import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = ("Windows", "Linux", "macOS")


def load_entries():
    data = json.loads((ROOT / "data/changelog.json").read_text())
    ids, previous_date, dated_seen = set(), date.max, False
    for entry in data["entries"]:
        identifier = entry["id"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", identifier) or identifier in ids:
            raise ValueError(f"Invalid or duplicate entry ID: {identifier}")
        ids.add(identifier)
        if entry["date"]:
            current = date.fromisoformat(entry["date"])
            if current > previous_date:
                raise ValueError("Dated entries must be newest first")
            if entry["kind"] == "Proposed":
                raise ValueError("Proposed changes must not carry a release date")
            previous_date, dated_seen = current, True
        elif dated_seen or entry["kind"] != "Proposed":
            raise ValueError("Undated proposed changes must precede the history")
        if not entry["title"] or not entry["changes"] or not entry["sources"]:
            raise ValueError(f"Missing content or source: {identifier}")
        if not entry["platforms"] or set(entry["platforms"]) - set(PLATFORMS):
            raise ValueError(f"Invalid platform: {identifier}")
        for source in entry["sources"]:
            url = urlparse(source["url"])
            if url.scheme != "https" or url.netloc != "github.com":
                raise ValueError(f"Source must be a GitHub HTTPS URL: {identifier}")
    return data


def html_entry(entry):
    pending = entry["date"] is None
    when = ("<span>Not yet released</span>" if pending else
            f'<time datetime="{entry["date"]}">{date.fromisoformat(entry["date"]).strftime("%b %d, %Y")}</time>')
    tags = "".join(f'<span class="change-platform">{platform}</span>' for platform in entry["platforms"])
    bullets = "".join(f"<li>{escape(text)}</li>" for text in entry["changes"])
    sources = "".join(f'<a href="{escape(source["url"], quote=True)}">{escape(source["label"])}</a>' for source in entry["sources"])
    kind_class = " change-breaking" if entry["kind"] == "Breaking change" else ""
    return f'''<article class="change-entry{' change-proposed' if pending else ''}" id="{entry['id']}" data-platforms="{' '.join(p.lower() for p in entry['platforms'])}" data-dated="{'false' if pending else 'true'}">
  <div class="change-date">{when}</div>
  <div class="change-body">
    <div class="change-tags"><span class="change-kind{kind_class}">{escape(entry['kind'])}</span>{tags}</div>
    <h3><a class="change-permalink" href="#{entry['id']}">{escape(entry['title'])}</a></h3>
    <ul>{bullets}</ul>
    <div class="change-sources" aria-label="Sources">{sources}</div>
  </div>
</article>'''


def render_html(data):
    pending = [entry for entry in data["entries"] if not entry["date"]]
    history = [entry for entry in data["entries"] if entry["date"]]
    years = list(dict.fromkeys(entry["date"][:4] for entry in history))
    sections = []
    if pending:
        sections.append('''<details class="change-section change-pending">
<summary><strong>Not yet released</strong><span>''' + str(len(pending)) + (' proposal' if len(pending) == 1 else ' proposals') + ''' under review</span></summary>
<p class="change-pending-note">These changes are not in the current downloads.</p>
''' + "\n".join(html_entry(entry) for entry in pending) + "\n</details>")
    for year in years:
        entries = [entry for entry in history if entry["date"].startswith(year)]
        sections.append(f'<section class="change-section change-year" id="year-{year}" aria-labelledby="heading-{year}"><h2 class="change-year-heading" id="heading-{year}">{year}</h2>\n' + "\n".join(html_entry(entry) for entry in entries) + "\n</section>")
    filters = '<button type="button" data-filter="all" aria-pressed="true">All platforms</button>'
    filters += "".join(f'<button type="button" data-filter="{platform.lower()}" aria-pressed="false">{platform}</button>' for platform in PLATFORMS)
    year_links = "".join(f'<a href="#year-{year}">{year}</a>' for year in years)
    return '''<!DOCTYPE html>
<!-- Generated by site/render_changelog.py from data/changelog.json. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="description" content="Dated changes to triage.zip collector coverage, platform support, and release behavior.">
  <title>Collector changelog | triage.zip</title>
  <link rel="stylesheet" href="css/styles.css">
  <link rel="stylesheet" href="css/changelog.css">
</head>
<body>
  <div class="background-accent"></div>
  <div class="container changelog-container">
    <nav class="changelog-nav" aria-label="Main navigation">
      <a class="changelog-brand" href="index.html">triage<span>.zip</span></a>
      <div><a href="index.html">Collector downloads</a><a href="https://github.com/Digital-Defense-Institute/triage.zip">GitHub</a></div>
    </nav>
    <main id="main-content">
      <header class="changelog-header">
        <h1>Collector changelog</h1>
        <p class="changelog-lede">Changes to evidence coverage, platform support, and how collectors are delivered.</p>
        <p class="changelog-explainer">Updates are tracked by date. The Velociraptor version identifies the engine; it does not identify every change to this collector.</p>
      </header>
      <div class="changelog-toolbar">
        <div class="changelog-filters" role="group" aria-label="Filter changes by platform" hidden>''' + filters + '''</div>
        <nav class="changelog-years" aria-label="Jump to year">''' + year_links + '''</nav>
      </div>
      <p class="changelog-count" role="status" aria-live="polite">''' + str(len(history)) + ''' dated updates</p>
      ''' + "\n".join(sections) + '''
      <aside class="changelog-history-note" aria-label="About this history">
        <h2>About these dates</h2>
        <p>''' + escape(data["history_note"]) + '''</p>
        <p>Check the <a href="index.html">download page</a> for the current engine version and build time. Earlier releases used a rolling latest download, so this history does not promise that an older binary is still available.</p>
      </aside>
    </main>
    <footer><p>Maintained by <a href="https://digitaldefenseinstitute.com/">Digital Defense Institute</a></p><p><a href="CHANGELOG.md">Read as Markdown</a> <span aria-hidden="true">/</span> <a href="https://github.com/Digital-Defense-Institute/triage.zip/issues/new/choose">Suggest a correction</a></p></footer>
  </div>
  <script src="js/changelog.js" defer></script>
</body>
</html>
'''


def render_markdown(data):
    parts = ["# Collector changelog", "Changes to triage.zip evidence coverage, platform support, and delivery. Dates track project changes; Velociraptor versions identify the upstream engine.", "Read the [hosted changelog](https://triage.zip/changelog.html).", "> " + data["history_note"], "<!-- Generated from data/changelog.json by site/render_changelog.py. -->"]
    pending_started = False
    for entry in data["entries"]:
        if not entry["date"] and not pending_started:
            parts += ["## Not yet released", "These proposals are under review and are not included in the current downloads."]
            pending_started = True
        heading = f'### {entry["title"]}' if not entry["date"] else f'## {entry["date"]} — {entry["title"]}'
        parts += [heading, f'**{entry["kind"]}** · ' + ", ".join(entry["platforms"]), "\n".join("- " + text for text in entry["changes"]), "Sources: " + "; ".join(f'[{source["label"]}]({source["url"]})' for source in entry["sources"])]
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files need updating")
    args = parser.parse_args()
    data = load_entries()
    outputs = {"changelog.html": render_html(data), "CHANGELOG.md": render_markdown(data)}
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        print("Regenerate the changelog: python3 site/render_changelog.py (" + ", ".join(stale) + ")", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
